const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync('dots/.config/quickshell/ii/modules/ii/sidebarRight/calendar/schedule.js', 'utf8').replace('.pragma library', ''), context);
const {key, date, addDays, week, minutes, initial, valid, occurrences, importPreset} = context;
assert.equal(key(addDays(date('2026-12-31'), 1)), '2027-01-01');
assert.equal(key(week(date('2026-11-01'))[0]), '2026-10-26');
assert.equal(key(addDays(date('2026-03-28'), 1)), '2026-03-29');
assert.equal(minutes('24:00'), -1);
assert.equal(minutes('12:60'), -1);
const data = initial();
assert(valid(data));
assert.equal(occurrences(data, date('2026-10-12')).length, 0);
data.routines = context.preset();
data.routines[0].startsOn = "2026-10-12";
assert(!occurrences({...data, presetEnabled:true}, date("2026-10-11")).some(e => e.id === "exercise"));
data.presetEnabled = true;
assert(occurrences(data, date('2026-10-12')).some(e => e.id === 'work-am'));
assert(!occurrences(data, date('2026-10-11')).some(e => e.id === 'work-am'));
data.exceptions['work-am@2026-10-12'] = {skipped: true};
assert(!occurrences(data, date('2026-10-12')).some(e => e.id === 'work-am'));
assert(occurrences(data, date('2026-10-13')).some(e => e.id === 'work-am'));
data.exceptions['work-am@2026-10-12'] = {start: 660, end: 870};
assert.equal(occurrences(data, date('2026-10-12')).find(e => e.id === 'work-am').start, 660);
assert(occurrences(data, date('2026-10-12')).find(e => e.id === 'lunch').conflict);
data.events.push({id:'overnight', title:'Night', date:'2026-10-12', start:1410, end:1500});
assert(valid(data));
const tail = occurrences(data, date('2026-10-13')).find(e => e.id === 'overnight');
assert.equal(tail.start, 0); assert.equal(tail.end, 60); assert(tail.continued);
assert.equal(tail.occurrenceId, 'overnight@2026-10-12');
data.exceptions['overnight@2026-10-12'] = {skipped:true};
assert(!occurrences(data, date('2026-10-13')).some(e => e.id === 'overnight'));
data.events[0].date = '2026-02-31'; assert(!valid(data));
const crowded = initial();
crowded.events = [[600,660], [630,690], [690,720]].map(([start,end],i) => ({id:String(i),title:'Event',date:'2026-10-12',start,end}));
const lanes = occurrences(crowded, date('2026-10-12'));
assert.equal(lanes[0].lanes,2); assert.equal(lanes[1].lane,1); assert.equal(lanes[2].lanes,1); assert(!lanes[2].conflict);
const preset = JSON.parse(fs.readFileSync('docs/calendar/example-preset.json', 'utf8'));
const imported = importPreset(initial(), preset);
assert(valid(imported));
assert.equal(imported.routines.length, 2);
assert.equal(imported.routines[0].id, 'preset/my-week/work');
assert.equal(occurrences(imported, date('2026-10-12')).find(e => e.id === 'preset/my-week/work').start, 630);
const reloaded = importPreset(imported, {...preset, routines: [preset.routines[1]]});
assert.equal(reloaded.routines.length, 1);
assert.equal(imported.routines.length, 2);
assert.throws(() => importPreset(imported, {...preset, routines: [{...preset.routines[0], start:'25:00'}]}));
assert.throws(() => importPreset(imported, {...preset, routines: [preset.routines[0], preset.routines[0]]}));
console.log('calendar schedule: passed');
